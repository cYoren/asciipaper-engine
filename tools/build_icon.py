#!/usr/bin/env python3
"""Build the asciipaper "Sunrise" icon for every platform from one glyph grid.

Glyphs are drawn as rectangles (no fonts), so the same shapes work in SVG,
Android vector drawables and rasterised PNG/ICO. Run from the repo root:
    python3 tools/build_icon.py
Needs rsvg-convert and ImageMagick (magick) for the raster outputs.
"""
import json, os, subprocess, tempfile

INK, MINT, DEEP = "#080d0e", "#8de5d7", "#2a6b67"
N, PAD = 8, 8                       # 8x8 cells inside a 128 tile
C = (128 - 2 * PAD) / N             # cell size (14)

# The scene: a sun of # rising over a - horizon, its reflection in : and .
GRID = [
    "        ",
    "   ++   ",
    "  +##+  ",
    " +####+ ",
    " ###### ",
    "--------",
    " :====: ",
    "  .::.  ",
]


def glyph_rects(ch, x, y):
    """Rectangles (x, y, w, h) that draw one glyph in the cell at x, y."""
    u = C / 14  # design unit: shapes are drawn on a 14x14 cell
    R = lambda a, b, w, h: (x + a * u, y + b * u, w * u, h * u)
    return {
        "#": [R(1, 3, 12, 3), R(1, 8, 12, 3), R(3, 1, 3, 12), R(8, 1, 3, 12)],
        "+": [R(2, 5.5, 10, 3), R(5.5, 2, 3, 10)],
        "-": [R(0, 5.5, 14, 3)],
        "=": [R(1, 3, 12, 3), R(1, 8, 12, 3)],
        ":": [R(5.5, 2, 3, 3), R(5.5, 9, 3, 3)],
        ".": [R(5.5, 9, 3, 3)],
    }.get(ch, [])


def rects():
    """(color, rect) for every glyph; the sky and sun are mint, the water deep."""
    out = []
    for row, line in enumerate(GRID):
        for col, ch in enumerate(line):
            color = MINT if row <= 5 else DEEP
            out += [(color, r) for r in glyph_rects(ch, PAD + col * C, PAD + row * C)]
    return out


def path(rs):
    return "".join(f"M{x:g},{y:g}h{w:g}v{h:g}h{-w:g}z" for x, y, w, h in rs)


TILE = "M28,0h72a28,28 0 0 1 28,28v72a28,28 0 0 1 -28,28h-72a28,28 0 0 1 -28,-28v-72a28,28 0 0 1 28,-28z"


def by_color():
    groups = {}
    for color, r in rects():
        groups.setdefault(color, []).append(r)
    return groups


def svg(rounded=True):
    bg = f'<path d="{TILE}" fill="{INK}"/>' if rounded else f'<rect width="128" height="128" fill="{INK}"/>'
    body = "".join(f'<path d="{path(rs)}" fill="{c}"/>' for c, rs in by_color().items())
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128">{bg}{body}</svg>\n'


def android_vector():
    paths = "\n".join(f'    <path android:fillColor="{c}" android:pathData="{path(rs)}"/>' for c, rs in by_color().items())
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build_icon.py; edit that script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp"
    android:viewportWidth="128" android:viewportHeight="128">
    <path android:fillColor="{INK}" android:pathData="{TILE}"/>
{paths}
</vector>
'''


def write(p, s):
    os.makedirs(os.path.dirname(p) or ".", exist_ok=True)
    with open(p, "w") as f:
        f.write(s)


def png(src_svg, out, size):
    subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), src_svg, "-o", out], check=True)


def main():
    write("io.github.cyoren.asciipaper.svg", svg())
    write("docs/icon.svg", svg())
    write("android/app/src/main/res/drawable/icon.xml", android_vector())
    with tempfile.TemporaryDirectory() as t:
        rounded, square = f"{t}/r.svg", f"{t}/s.svg"
        write(rounded, svg())
        write(square, svg(rounded=False))
        sizes = [16, 24, 32, 48, 64, 128, 256]
        for s in sizes:
            png(rounded, f"{t}/{s}.png", s)
        subprocess.run(["magick", *[f"{t}/{s}.png" for s in sizes], "windows/asciipaper.ico"], check=True)
        # Apple draws its own rounded mask, so it gets the full-bleed square.
        appicon = "apple/Resources/Assets.xcassets/AppIcon.appiconset"
        os.makedirs(appicon, exist_ok=True)
        png(square, f"{appicon}/icon-1024.png", 1024)
        mac = [(16, 1), (16, 2), (32, 1), (32, 2), (128, 1), (128, 2), (256, 1), (256, 2), (512, 1), (512, 2)]
        images = [{"idiom": "universal", "platform": "ios", "size": "1024x1024", "filename": "icon-1024.png"}]
        for pt, sc in mac:
            name = f"mac-{pt}@{sc}x.png"
            png(square, f"{appicon}/{name}", pt * sc)
            images.append({"idiom": "mac", "size": f"{pt}x{pt}", "scale": f"{sc}x", "filename": name})
        write(f"{appicon}/Contents.json", json.dumps({"images": images, "info": {"version": 1, "author": "xcode"}}, indent=2) + "\n")
        write("apple/Resources/Assets.xcassets/Contents.json", json.dumps({"info": {"version": 1, "author": "xcode"}}, indent=2) + "\n")


if __name__ == "__main__":
    main()
